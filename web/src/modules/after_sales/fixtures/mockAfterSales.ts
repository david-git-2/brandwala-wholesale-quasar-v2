export const computeHubSummary = (cases: AfterSalesCase[]): AfterSalesHubSummary => {
  const openStatuses = new Set(['draft', 'pending_approval', 'approved', 'awaiting_receipt', 'received', 'inspecting', 'executing']);
  const now = new Date();
  const monthStart = new Date(now.getFullYear(), now.getMonth(), 1);

  return {
    open_cases: cases.filter((c) => openStatuses.has(c.status)).length,
    pending_approval: cases.filter((c) => c.status === 'pending_approval').length,
    awaiting_receipt: cases.filter((c) => c.status === 'awaiting_receipt' || c.status === 'approved').length,
    wholesale_count: cases.filter((c) => c.source_channel === 'wholesale' && openStatuses.has(c.status)).length,
    dropship_count: cases.filter((c) => c.source_channel === 'dropship' && openStatuses.has(c.status)).length,
    closed_this_month: cases.filter((c) => {
      if (c.status !== 'closed' || !c.closed_at) return false;
      return new Date(c.closed_at) >= monthStart;
    }).length,
  };
};

