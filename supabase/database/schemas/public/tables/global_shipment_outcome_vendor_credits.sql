CREATE TABLE public.global_shipment_outcome_vendor_credits (
  id                      bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  parent_tenant_id        bigint                   NOT NULL,
  shipment_id             bigint                   NOT NULL,
  shipment_item_id        bigint                   NOT NULL,
  outcome_id              bigint                   NOT NULL,
  quantity                integer                  NOT NULL,
  previous_purchase_price numeric                  NOT NULL,
  new_purchase_price      numeric                  NOT NULL,
  credit_amount           numeric                  NOT NULL,
  created_by_email        text,
  created_at              timestamp with time zone DEFAULT now() NOT NULL,
  updated_at              timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX global_shipment_outcome_vendor_credits_outcome_idx ON public.global_shipment_outcome_vendor_credits (outcome_id);

CREATE INDEX global_shipment_outcome_vendor_credits_shipment_idx ON public.global_shipment_outcome_vendor_credits (shipment_id);

CREATE TRIGGER trg_global_shipment_outcome_vendor_credits_set_updated_at
  BEFORE UPDATE ON public.global_shipment_outcome_vendor_credits
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE POLICY global_shipment_outcome_vendor_credits_all ON public.global_shipment_outcome_vendor_credits
  TO authenticated
  USING (public.user_can_manage_parent_tenant(parent_tenant_id))
  WITH CHECK (public.user_can_manage_parent_tenant(parent_tenant_id));

