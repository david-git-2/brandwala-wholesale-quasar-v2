CREATE TABLE public.stock_physical_counts (
  id               bigint                             GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  parent_tenant_id bigint                             NOT NULL,
  location_id      bigint,
  status           public.stock_physical_count_status DEFAULT 'draft'::public.stock_physical_count_status NOT NULL,
  notes            text,
  movement_id      bigint,
  created_by_email text,
  created_at       timestamp with time zone           DEFAULT now() NOT NULL,
  updated_at       timestamp with time zone           DEFAULT now() NOT NULL,
  submitted_at     timestamp with time zone,
  approved_at      timestamp with time zone
);

CREATE INDEX stock_physical_counts_tenant_status_idx ON public.stock_physical_counts (parent_tenant_id, status);

CREATE POLICY stock_physical_counts_select ON public.stock_physical_counts
  FOR SELECT
  TO authenticated
  USING (public.user_can_manage_parent_tenant(parent_tenant_id));

ALTER TABLE public.stock_physical_counts
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.stock_physical_counts
  ADD CONSTRAINT stock_physical_counts_location_id_fkey FOREIGN KEY (location_id) REFERENCES public.stock_locations(id);

ALTER TABLE public.stock_physical_counts
  ADD CONSTRAINT stock_physical_counts_movement_id_fkey FOREIGN KEY (movement_id) REFERENCES public.stock_movements(id);

ALTER TABLE public.stock_physical_counts
  ADD CONSTRAINT stock_physical_counts_pkey PRIMARY KEY (id);

ALTER TABLE public.stock_physical_counts
  ADD CONSTRAINT stock_physical_counts_parent_tenant_id_fkey FOREIGN KEY (parent_tenant_id) REFERENCES public.tenants(id);

GRANT ALL ON public.stock_physical_counts TO anon;

GRANT ALL ON public.stock_physical_counts TO authenticated;

