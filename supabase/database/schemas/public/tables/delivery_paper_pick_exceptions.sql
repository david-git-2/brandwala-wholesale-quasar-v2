CREATE TABLE public.delivery_paper_pick_exceptions (
  id                     bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  delivery_paper_id      bigint                   NOT NULL,
  delivery_paper_line_id bigint                   NOT NULL,
  requested_qty          integer                  NOT NULL,
  picked_qty             integer                  NOT NULL,
  reason                 text,
  created_by_email       text,
  created_at             timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX delivery_paper_pick_exceptions_paper_idx ON public.delivery_paper_pick_exceptions (delivery_paper_id);

CREATE POLICY delivery_paper_pick_exceptions_select ON public.delivery_paper_pick_exceptions
  FOR SELECT
  TO authenticated
  USING ((EXISTS ( SELECT 1
   FROM public.delivery_paper dp
  WHERE ((dp.id = delivery_paper_pick_exceptions.delivery_paper_id) AND public.user_can_manage_parent_tenant(dp.parent_tenant_id)))));

ALTER TABLE public.delivery_paper_pick_exceptions
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.delivery_paper_pick_exceptions
  ADD CONSTRAINT delivery_paper_pick_exceptions_delivery_paper_id_fkey FOREIGN KEY (delivery_paper_id) REFERENCES public.delivery_paper(id) ON DELETE CASCADE;

ALTER TABLE public.delivery_paper_pick_exceptions
  ADD CONSTRAINT delivery_paper_pick_exceptions_delivery_paper_line_id_fkey FOREIGN KEY (delivery_paper_line_id) REFERENCES public.delivery_paper_line(id) ON DELETE CASCADE;

ALTER TABLE public.delivery_paper_pick_exceptions
  ADD CONSTRAINT delivery_paper_pick_exceptions_pkey PRIMARY KEY (id);

