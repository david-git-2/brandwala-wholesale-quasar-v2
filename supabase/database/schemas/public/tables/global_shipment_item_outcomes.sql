CREATE TABLE public.global_shipment_item_outcomes (
  id               bigint                                GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  parent_tenant_id bigint                                NOT NULL,
  shipment_item_id bigint                                NOT NULL,
  quantity         integer                               NOT NULL,
  kind             public.global_shipment_outcome_kind   NOT NULL,
  reason           public.global_shipment_outcome_reason NOT NULL,
  purchase_price   numeric                               DEFAULT 0 NOT NULL,
  cost             numeric,
  description      text,
  batch_label      text,
  created_at       timestamp with time zone              DEFAULT now() NOT NULL,
  updated_at       timestamp with time zone              DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX global_shipment_item_outcomes_one_ordered_idx ON public.global_shipment_item_outcomes (shipment_item_id)
  WHERE reason = 'ordered'::public.global_shipment_outcome_reason;

CREATE INDEX global_shipment_item_outcomes_parent_idx ON public.global_shipment_item_outcomes (parent_tenant_id);

CREATE INDEX global_shipment_item_outcomes_item_idx ON public.global_shipment_item_outcomes (shipment_item_id);

CREATE TRIGGER trg_global_shipment_item_outcomes_set_updated_at
  BEFORE UPDATE ON public.global_shipment_item_outcomes
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE POLICY global_shipment_item_outcomes_all ON public.global_shipment_item_outcomes
  TO authenticated
  USING (public.user_can_manage_parent_tenant(parent_tenant_id))
  WITH CHECK (public.user_can_manage_parent_tenant(parent_tenant_id));

ALTER TABLE public.global_shipment_item_outcomes
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.global_shipment_item_outcomes
  ADD CONSTRAINT global_shipment_item_outcomes_cost_check CHECK (cost IS NULL OR cost >= 0::numeric);

ALTER TABLE public.global_shipment_item_outcomes
  ADD CONSTRAINT global_shipment_item_outcomes_pkey PRIMARY KEY (id);

ALTER TABLE public.global_shipment_item_outcomes
  ADD CONSTRAINT global_shipment_item_outcomes_purchase_price_check CHECK (purchase_price >= 0::numeric);

ALTER TABLE public.global_shipment_item_outcomes
  ADD CONSTRAINT global_shipment_item_outcomes_quantity_check CHECK (quantity >= 0);

ALTER TABLE public.global_shipment_item_outcomes
  ADD CONSTRAINT global_shipment_item_outcomes_shipment_item_id_fkey FOREIGN KEY (shipment_item_id) REFERENCES public.global_shipment_items(id) ON DELETE CASCADE;

ALTER TABLE public.global_shipment_item_outcomes
  ADD CONSTRAINT global_shipment_item_outcomes_parent_tenant_id_fkey FOREIGN KEY (parent_tenant_id) REFERENCES public.tenants(id) ON DELETE CASCADE;

GRANT ALL ON public.global_shipment_item_outcomes TO anon;

