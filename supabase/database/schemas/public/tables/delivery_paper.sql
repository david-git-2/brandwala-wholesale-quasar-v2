CREATE TABLE public.delivery_paper (
  id               bigint                            GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  parent_tenant_id bigint                            NOT NULL,
  source_type      public.delivery_paper_source_type NOT NULL,
  source_id        bigint                            NOT NULL,
  delivery_date    date,
  profile_id       bigint,
  note             text,
  status           public.delivery_paper_status      DEFAULT 'draft'::public.delivery_paper_status NOT NULL,
  created_at       timestamp with time zone          DEFAULT now() NOT NULL,
  updated_at       timestamp with time zone          DEFAULT now() NOT NULL,
  dispatched_at    timestamp with time zone
);

CREATE INDEX delivery_paper_parent_profile_idx ON public.delivery_paper (parent_tenant_id, profile_id)
  WHERE profile_id IS NOT NULL;

CREATE INDEX delivery_paper_source_idx ON public.delivery_paper (source_type, source_id);

CREATE TRIGGER trg_delivery_paper_set_updated_at
  BEFORE UPDATE ON public.delivery_paper
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE POLICY delivery_paper_select ON public.delivery_paper
  FOR SELECT
  TO authenticated
  USING ((public.user_can_manage_parent_tenant(parent_tenant_id) OR (EXISTS ( SELECT 1
   FROM public.tenants t
  WHERE (((t.id = delivery_paper.parent_tenant_id) OR (t.parent_id = delivery_paper.parent_tenant_id)) AND public.is_tenant_staff(t.id))))));

ALTER TABLE public.delivery_paper
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.delivery_paper
  ADD CONSTRAINT delivery_paper_pkey PRIMARY KEY (id);

ALTER TABLE public.delivery_paper
  ADD CONSTRAINT delivery_paper_profile_id_fkey FOREIGN KEY (profile_id) REFERENCES public.profiles(id);

ALTER TABLE public.delivery_paper
  ADD CONSTRAINT delivery_paper_parent_tenant_id_fkey FOREIGN KEY (parent_tenant_id) REFERENCES public.tenants(id);

GRANT ALL ON public.delivery_paper TO anon;

GRANT ALL ON public.delivery_paper TO authenticated;

GRANT ALL ON public.delivery_paper TO service_role;