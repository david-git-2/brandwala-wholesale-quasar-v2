CREATE TABLE public.delivery_paper_line (
  id                        bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  delivery_paper_id         bigint                   NOT NULL,
  preorder_demand_id        bigint                   NOT NULL,
  global_stock_id           bigint,
  dispatched_global_stock_id bigint,
  note                      text,
  created_at                timestamp with time zone DEFAULT now() NOT NULL,
  updated_at                timestamp with time zone DEFAULT now() NOT NULL,
  splits                    jsonb                    DEFAULT '[]'::jsonb NOT NULL,
  unit_cost_landed_snapshot numeric
);

CREATE INDEX delivery_paper_line_demand_idx ON public.delivery_paper_line (preorder_demand_id);

CREATE INDEX delivery_paper_line_paper_idx ON public.delivery_paper_line (delivery_paper_id);

CREATE UNIQUE INDEX delivery_paper_line_paper_demand_stock_uidx ON public.delivery_paper_line (delivery_paper_id, preorder_demand_id, global_stock_id)
  WHERE global_stock_id IS NOT NULL;

CREATE UNIQUE INDEX delivery_paper_line_paper_demand_no_stock_uidx ON public.delivery_paper_line (delivery_paper_id, preorder_demand_id)
  WHERE global_stock_id IS NULL AND dispatched_global_stock_id IS NULL;

CREATE TRIGGER trg_delivery_paper_line_set_updated_at
  BEFORE UPDATE ON public.delivery_paper_line
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE POLICY delivery_paper_line_select ON public.delivery_paper_line
  FOR SELECT
  TO authenticated
  USING ((EXISTS ( SELECT 1
   FROM public.delivery_paper dp
  WHERE ((dp.id = delivery_paper_line.delivery_paper_id) AND (public.user_can_manage_parent_tenant(dp.parent_tenant_id) OR (EXISTS ( SELECT 1
           FROM public.tenants t
          WHERE (((t.id = dp.parent_tenant_id) OR (t.parent_id = dp.parent_tenant_id)) AND public.is_tenant_staff(t.id)))))))));

ALTER TABLE public.delivery_paper_line
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.delivery_paper_line
  ADD CONSTRAINT delivery_paper_line_delivery_paper_id_fkey FOREIGN KEY (delivery_paper_id) REFERENCES public.delivery_paper(id) ON DELETE CASCADE;

ALTER TABLE public.delivery_paper_line
  ADD CONSTRAINT delivery_paper_line_pkey PRIMARY KEY (id);

ALTER TABLE public.delivery_paper_line
  ADD CONSTRAINT delivery_paper_line_splits_valid CHECK (public.validate_delivery_paper_line_splits(splits));

ALTER TABLE public.delivery_paper_line
  ADD CONSTRAINT delivery_paper_line_global_stock_id_fkey FOREIGN KEY (global_stock_id) REFERENCES public.global_stocks(id) ON DELETE SET NULL;

ALTER TABLE public.delivery_paper_line
  ADD CONSTRAINT delivery_paper_line_preorder_demand_id_fkey FOREIGN KEY (preorder_demand_id) REFERENCES public.preorder_demand(id) ON DELETE CASCADE;

GRANT ALL ON public.delivery_paper_line TO anon;

