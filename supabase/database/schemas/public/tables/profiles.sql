CREATE TABLE public.profiles (
  id                  bigint                    GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  parent_tenant_id    bigint                    NOT NULL,
  profile_type        public.profile_party_type DEFAULT 'customer'::public.profile_party_type NOT NULL,
  subject_id          bigint                    NOT NULL,
  name                text                      NOT NULL,
  email               text,
  phone               text,
  phone_country_code  text                      DEFAULT '+880'::text NOT NULL,
  address             text,
  is_phone_unique     boolean                   DEFAULT true NOT NULL,
  accent_color        text,
  is_active           boolean                   DEFAULT true NOT NULL,
  deleted_at          timestamp with time zone,
  created_at          timestamp with time zone  DEFAULT now() NOT NULL,
  updated_at          timestamp with time zone  DEFAULT now() NOT NULL,
  customer_group_id   bigint,
  operating_tenant_id bigint
);

CREATE INDEX profiles_parent_tenant_id_idx ON public.profiles (parent_tenant_id);

CREATE INDEX profiles_profile_type_idx ON public.profiles (profile_type);

CREATE INDEX profiles_customer_group_id_idx ON public.profiles (customer_group_id)
  WHERE profile_type = 'customer'::public.profile_party_type;

CREATE UNIQUE INDEX profiles_customer_parent_phone_uidx ON public.profiles (parent_tenant_id, phone_country_code, phone)
  WHERE profile_type = 'customer'::public.profile_party_type AND phone IS NOT NULL AND btrim(phone) <> ''::text AND is_phone_unique;

CREATE INDEX profiles_operating_tenant_id_idx ON public.profiles (operating_tenant_id)
  WHERE profile_type = 'customer'::public.profile_party_type;

CREATE UNIQUE INDEX profiles_parent_phone_uidx ON public.profiles (parent_tenant_id, phone_country_code, phone)
  WHERE phone IS NOT NULL AND btrim(phone) <> ''::text AND is_phone_unique;

CREATE TRIGGER trg_profiles_set_updated_at
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE POLICY profiles_select ON public.profiles
  FOR SELECT
  TO authenticated
  USING ((public.has_active_tenant_membership(parent_tenant_id) OR public.user_can_manage_parent_tenant(parent_tenant_id) OR (EXISTS ( SELECT 1
   FROM public.memberships m
  WHERE ((m.tenant_id = profiles.parent_tenant_id) AND (lower(TRIM(BOTH FROM m.email)) = public.current_user_email()) AND m.is_active)))));

CREATE POLICY profiles_write ON public.profiles
  TO authenticated
  USING (public.membership_has_module_action(parent_tenant_id, 'billing_profile'::text, 'edit'::text))
  WITH CHECK (public.membership_has_module_action(parent_tenant_id, 'billing_profile'::text, 'edit'::text));

