CREATE TABLE public.stock_locations (
  id                 bigint                     GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  parent_tenant_id   bigint                     NOT NULL,
  code               text                       NOT NULL,
  name               text                       NOT NULL,
  kind               public.stock_location_kind DEFAULT 'bin'::public.stock_location_kind NOT NULL,
  is_default         boolean                    DEFAULT false NOT NULL,
  is_pickable        boolean                    DEFAULT true NOT NULL,
  sort_order         integer                    DEFAULT 0 NOT NULL,
  is_active          boolean                    DEFAULT true NOT NULL,
  created_at         timestamp with time zone   DEFAULT now() NOT NULL,
  updated_at         timestamp with time zone   DEFAULT now() NOT NULL,
  parent_location_id bigint
);

CREATE INDEX stock_locations_parent_sort_idx ON public.stock_locations (parent_tenant_id, sort_order);

CREATE UNIQUE INDEX stock_locations_one_default_per_parent_idx ON public.stock_locations (parent_tenant_id)
  WHERE is_default = true AND is_active = true;

CREATE INDEX stock_locations_parent_active_idx ON public.stock_locations (parent_tenant_id, is_active);

CREATE INDEX stock_locations_parent_location_idx ON public.stock_locations (parent_location_id);

CREATE TRIGGER trg_stock_locations_updated_at
  BEFORE UPDATE ON public.stock_locations
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE POLICY stock_locations_all ON public.stock_locations
  TO authenticated
  USING (public.user_can_manage_parent_tenant(parent_tenant_id))
  WITH CHECK (public.user_can_manage_parent_tenant(parent_tenant_id));

CREATE POLICY stock_locations_select ON public.stock_locations
  FOR SELECT
  TO authenticated
  USING ((public.user_can_manage_parent_tenant(parent_tenant_id) OR (EXISTS ( SELECT 1
   FROM public.memberships m
  WHERE ((m.tenant_id = stock_locations.parent_tenant_id) AND (lower(TRIM(BOTH FROM m.email)) = public.current_user_email()) AND (m.is_active = true))))));

ALTER TABLE public.stock_locations
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.stock_locations
  ADD CONSTRAINT stock_locations_code_not_blank CHECK (length(TRIM(BOTH FROM code)) > 0);

ALTER TABLE public.stock_locations
  ADD CONSTRAINT stock_locations_name_not_blank CHECK (length(TRIM(BOTH FROM name)) > 0);

ALTER TABLE public.stock_locations
  ADD CONSTRAINT stock_locations_parent_code_unique UNIQUE (parent_tenant_id, code);

ALTER TABLE public.stock_locations
  ADD CONSTRAINT stock_locations_pkey PRIMARY KEY (id);

ALTER TABLE public.stock_locations
  ADD CONSTRAINT stock_locations_parent_location_id_fkey FOREIGN KEY (parent_location_id) REFERENCES public.stock_locations(id) ON DELETE CASCADE;

ALTER TABLE public.stock_locations
  ADD CONSTRAINT stock_locations_parent_tenant_id_fkey FOREIGN KEY (parent_tenant_id) REFERENCES public.tenants(id) ON DELETE CASCADE;

GRANT ALL ON public.stock_locations TO anon;

GRANT ALL ON public.stock_locations TO authenticated;

GRANT ALL ON public.stock_locations TO service_role;