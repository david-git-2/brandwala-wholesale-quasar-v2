CREATE TABLE public.stock_physical_count_lines (
  id              bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  count_id        bigint                   NOT NULL,
  global_stock_id bigint                   NOT NULL,
  system_qty      integer                  DEFAULT 0 NOT NULL,
  counted_qty     integer,
  recount_qty     integer,
  approved_qty    integer,
  created_at      timestamp with time zone DEFAULT now() NOT NULL,
  updated_at      timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX stock_physical_count_lines_count_idx ON public.stock_physical_count_lines (count_id);

CREATE POLICY stock_physical_count_lines_select ON public.stock_physical_count_lines
  FOR SELECT
  TO authenticated
  USING ((EXISTS ( SELECT 1
   FROM public.stock_physical_counts c
  WHERE ((c.id = stock_physical_count_lines.count_id) AND public.user_can_manage_parent_tenant(c.parent_tenant_id)))));

ALTER TABLE public.stock_physical_count_lines
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.stock_physical_count_lines
  ADD CONSTRAINT stock_physical_count_lines_global_stock_id_fkey FOREIGN KEY (global_stock_id) REFERENCES public.global_stocks(id);

ALTER TABLE public.stock_physical_count_lines
  ADD CONSTRAINT stock_physical_count_lines_pkey PRIMARY KEY (id);

ALTER TABLE public.stock_physical_count_lines
  ADD CONSTRAINT stock_physical_count_lines_unique_stock UNIQUE (count_id, global_stock_id);

ALTER TABLE public.stock_physical_count_lines
  ADD CONSTRAINT stock_physical_count_lines_count_id_fkey FOREIGN KEY (count_id) REFERENCES public.stock_physical_counts(id) ON DELETE CASCADE;

GRANT ALL ON public.stock_physical_count_lines TO anon;

GRANT ALL ON public.stock_physical_count_lines TO authenticated;

GRANT ALL ON public.stock_physical_count_lines TO service_role;