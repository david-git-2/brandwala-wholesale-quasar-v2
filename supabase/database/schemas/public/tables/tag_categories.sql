CREATE TABLE public.tag_categories (
  id          bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  module_key  text                     NOT NULL,
  code        text                     NOT NULL,
  name        text                     NOT NULL,
  cardinality text                     NOT NULL,
  is_system   boolean                  DEFAULT true NOT NULL,
  tenant_id   bigint,
  sort_order  integer,
  is_active   boolean                  DEFAULT true NOT NULL,
  created_at  timestamp with time zone DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX tag_categories_tenant_unique ON public.tag_categories (tenant_id, module_key, code)
  WHERE tenant_id IS NOT NULL;

CREATE UNIQUE INDEX tag_categories_system_unique ON public.tag_categories (module_key, code)
  WHERE tenant_id IS NULL;

CREATE POLICY tag_categories_delete ON public.tag_categories
  FOR DELETE
  TO authenticated
  USING (((is_system = false) AND (tenant_id IS NOT NULL) AND public.has_active_tenant_membership(tenant_id)));

CREATE POLICY tag_categories_insert ON public.tag_categories
  FOR INSERT
  TO authenticated
  WITH CHECK (((is_system = false) AND (tenant_id IS NOT NULL) AND public.has_active_tenant_membership(tenant_id)));

CREATE POLICY tag_categories_select ON public.tag_categories
  FOR SELECT
  TO authenticated
  USING (((is_system = true) OR (tenant_id IS NULL) OR ((tenant_id IS NOT NULL) AND public.has_active_tenant_membership(tenant_id))));

CREATE POLICY tag_categories_update ON public.tag_categories
  FOR UPDATE
  TO authenticated
  USING (((is_system = false) AND (tenant_id IS NOT NULL) AND public.has_active_tenant_membership(tenant_id)));

ALTER TABLE public.tag_categories
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.tag_categories
  ADD CONSTRAINT tag_categories_cardinality_check CHECK (cardinality = ANY (ARRAY['single'::text, 'many'::text]));

ALTER TABLE public.tag_categories
  ADD CONSTRAINT tag_categories_pkey PRIMARY KEY (id);

ALTER TABLE public.tag_categories
  ADD CONSTRAINT tag_categories_tenant_id_fkey FOREIGN KEY (tenant_id) REFERENCES public.tenants(id) ON DELETE CASCADE;

GRANT ALL ON public.tag_categories TO anon;

GRANT ALL ON public.tag_categories TO authenticated;

GRANT ALL ON public.tag_categories TO service_role;