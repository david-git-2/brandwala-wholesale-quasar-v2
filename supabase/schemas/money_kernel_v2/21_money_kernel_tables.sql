-- 003 cashbook_accounts (default pot FK deferred)
CREATE TABLE IF NOT EXISTS money_kernel.cashbook_accounts (
  id                            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id                     bigint NOT NULL REFERENCES public.tenants (id),
  entity_type                   text NOT NULL,
  entity_id                     bigint NOT NULL,
  profile_id                    bigint,
  available_balance             numeric(18, 4) NOT NULL DEFAULT 0,
  pending_balance               numeric(18, 4) NOT NULL DEFAULT 0,
  locked_balance                numeric(18, 4) NOT NULL DEFAULT 0,
  default_cashbook_lot_id bigint,
  created_at                    timestamptz NOT NULL DEFAULT now(),
  updated_at                    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, entity_type, entity_id),
  CONSTRAINT chk_tenant_entity_matches
    CHECK (entity_type <> 'tenant' OR entity_id = tenant_id),
  CONSTRAINT uq_cashbook_accounts_tenant_id UNIQUE (tenant_id, id)
);

-- 004 cashbook_points
CREATE TABLE IF NOT EXISTS money_kernel.cashbook_points (
  id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id           bigint NOT NULL REFERENCES public.tenants (id),
  cashbook_account_id bigint NOT NULL REFERENCES money_kernel.cashbook_accounts (id) ON DELETE RESTRICT,
  code                text NOT NULL,
  name                text NOT NULL,
  is_active           boolean NOT NULL DEFAULT true,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (cashbook_account_id, code),
  CONSTRAINT uq_cashbook_points_tenant_id UNIQUE (tenant_id, id)
);

