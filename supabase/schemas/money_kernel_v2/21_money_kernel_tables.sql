-- 007 pays
CREATE TABLE IF NOT EXISTS money_kernel.pays (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint NOT NULL REFERENCES public.tenants (id),
  kind             text NOT NULL CHECK (kind IN ('deposit', 'withdrawal', 'transfer', 'payment')),
  from_lot_id      bigint,
  to_lot_id        bigint,
  amount           numeric(18, 4) NOT NULL CHECK (amount > 0),
  currency_code    text NOT NULL DEFAULT 'BDT' REFERENCES money_kernel.currencies (code),
  books_amount     numeric(18, 4) NOT NULL,
  books_rate       numeric(15, 6) NOT NULL DEFAULT 1,
  exchange_rate    numeric(15, 6) NOT NULL DEFAULT 1,
  payment_date     date NOT NULL DEFAULT CURRENT_DATE,
  status           text NOT NULL DEFAULT 'posted' CHECK (status IN ('posted', 'voided')),
  voided_at        timestamptz,
  voided_by        uuid,
  idempotency_key  text,
  request_hash     text,
  from_balance_after numeric(18, 4),
  to_balance_after   numeric(18, 4),
  refs             jsonb NOT NULL DEFAULT '{}'::jsonb,
  meta             jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by       uuid,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CHECK (from_lot_id IS NOT NULL OR to_lot_id IS NOT NULL),
  CHECK (from_lot_id IS DISTINCT FROM to_lot_id),
  CHECK (pg_column_size(meta) < 8192),
  CONSTRAINT uq_pays_tenant_id UNIQUE (tenant_id, id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_pays_idempotency
  ON money_kernel.pays (tenant_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

