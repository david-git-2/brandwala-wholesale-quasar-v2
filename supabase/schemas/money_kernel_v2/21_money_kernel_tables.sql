-- 001 currencies
CREATE TABLE IF NOT EXISTS money_kernel.currencies (
  code         text PRIMARY KEY CHECK (code ~ '^[A-Z]{3}$'),
  minor_units  smallint NOT NULL CHECK (minor_units BETWEEN 0 AND 4),
  name         text NOT NULL
);

