-- 010 bills
CREATE TABLE IF NOT EXISTS money_kernel.bills (
  id                      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id               bigint NOT NULL REFERENCES public.tenants (id),
  kind                    text NOT NULL REFERENCES money_kernel.bill_kind_registry (kind),
  status                  text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'issued', 'partial', 'paid', 'voided', 'written_off')),
  invoice_no              text,
  request_hash            text,
  invoice_date            date NOT NULL DEFAULT CURRENT_DATE,
  due_date                date,
  from_profile_id         bigint,
  to_profile_id           bigint,
  counterparty_profile_id bigint,
  counterparty_tenant_id  bigint,
  currency_code           text NOT NULL DEFAULT 'BDT' REFERENCES money_kernel.currencies (code),
  total_amount            numeric(18, 4) NOT NULL DEFAULT 0,
  paid_amount             numeric(18, 4) NOT NULL DEFAULT 0,
  due_amount              numeric(18, 4) NOT NULL DEFAULT 0,
  written_off_amount      numeric(18, 4) NOT NULL DEFAULT 0,
  parent_bill_id          bigint,
  source_entity           text,
  source_type             text,
  source_id               text,
  source_key              text,
  idempotency_key         text,
  meta                    jsonb NOT NULL DEFAULT '{}'::jsonb,
  note                    text,
  created_by              uuid,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_amounts_non_negative
    CHECK (total_amount >= 0 AND paid_amount >= 0 AND due_amount >= 0 AND written_off_amount >= 0),
  CONSTRAINT chk_bill_amount_identity
    CHECK (
      status = 'voided'
      OR paid_amount + due_amount + written_off_amount = total_amount
    ),
  CONSTRAINT chk_bills_meta_size CHECK (pg_column_size(meta) < 8192),
  CONSTRAINT uq_bills_tenant_id UNIQUE (tenant_id, id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_bills_invoice_no
