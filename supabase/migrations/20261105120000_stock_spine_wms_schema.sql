-- Stock spine WMS: issue_outbound enum, physical count + short-pick tables, delivery paper dispatch columns.

ALTER TYPE public.stock_movement_type ADD VALUE IF NOT EXISTS 'issue_outbound';
ALTER TYPE public.stock_movement_type ADD VALUE IF NOT EXISTS 'vendor_return';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'stock_physical_count_status') THEN
    CREATE TYPE public.stock_physical_count_status AS ENUM (
      'draft',
      'counting',
      'pending_approval',
      'posted',
      'cancelled'
    );
  END IF;
END $$;

ALTER TABLE public.delivery_paper
  ADD COLUMN IF NOT EXISTS dispatched_at timestamptz;

ALTER TABLE public.delivery_paper_line
  ADD COLUMN IF NOT EXISTS unit_cost_landed_snapshot numeric;

CREATE TABLE IF NOT EXISTS public.stock_physical_counts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_tenant_id bigint NOT NULL REFERENCES public.tenants(id),
  location_id bigint REFERENCES public.stock_locations(id),
  status public.stock_physical_count_status NOT NULL DEFAULT 'draft',
  notes text,
  movement_id bigint REFERENCES public.stock_movements(id),
  created_by_email text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  submitted_at timestamptz,
  approved_at timestamptz
);

CREATE INDEX IF NOT EXISTS stock_physical_counts_tenant_status_idx
  ON public.stock_physical_counts (parent_tenant_id, status);

CREATE TABLE IF NOT EXISTS public.stock_physical_count_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  count_id bigint NOT NULL REFERENCES public.stock_physical_counts(id) ON DELETE CASCADE,
  global_stock_id bigint NOT NULL REFERENCES public.global_stocks(id),
  system_qty integer NOT NULL DEFAULT 0,
  counted_qty integer,
  recount_qty integer,
  approved_qty integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT stock_physical_count_lines_unique_stock UNIQUE (count_id, global_stock_id)
);

CREATE INDEX IF NOT EXISTS stock_physical_count_lines_count_idx
  ON public.stock_physical_count_lines (count_id);

CREATE TABLE IF NOT EXISTS public.delivery_paper_pick_exceptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_paper_id bigint NOT NULL REFERENCES public.delivery_paper(id) ON DELETE CASCADE,
  delivery_paper_line_id bigint NOT NULL REFERENCES public.delivery_paper_line(id) ON DELETE CASCADE,
  requested_qty integer NOT NULL,
  picked_qty integer NOT NULL,
  reason text,
  created_by_email text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS delivery_paper_pick_exceptions_paper_idx
  ON public.delivery_paper_pick_exceptions (delivery_paper_id);

ALTER TABLE public.stock_physical_counts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_physical_count_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.delivery_paper_pick_exceptions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS stock_physical_counts_select ON public.stock_physical_counts;
CREATE POLICY stock_physical_counts_select ON public.stock_physical_counts
  FOR SELECT TO authenticated
  USING (public.user_can_manage_parent_tenant(parent_tenant_id));

DROP POLICY IF EXISTS stock_physical_count_lines_select ON public.stock_physical_count_lines;
CREATE POLICY stock_physical_count_lines_select ON public.stock_physical_count_lines
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.stock_physical_counts c
      WHERE c.id = stock_physical_count_lines.count_id
        AND public.user_can_manage_parent_tenant(c.parent_tenant_id)
    )
  );

DROP POLICY IF EXISTS delivery_paper_pick_exceptions_select ON public.delivery_paper_pick_exceptions;
CREATE POLICY delivery_paper_pick_exceptions_select ON public.delivery_paper_pick_exceptions
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.delivery_paper dp
      WHERE dp.id = delivery_paper_pick_exceptions.delivery_paper_id
        AND public.user_can_manage_parent_tenant(dp.parent_tenant_id)
    )
  );

GRANT SELECT ON public.stock_physical_counts TO authenticated, service_role;
GRANT SELECT ON public.stock_physical_count_lines TO authenticated, service_role;
GRANT SELECT ON public.delivery_paper_pick_exceptions TO authenticated, service_role;
