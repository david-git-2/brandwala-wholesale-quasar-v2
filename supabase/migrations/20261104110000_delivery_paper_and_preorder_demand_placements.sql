-- Delivery paper (outbound document) + preorder_demand vendor_placements JSON.
-- Replaces customer_deliveries / customer_delivery_lines naming from design doc.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'delivery_paper_source_type') THEN
    CREATE TYPE public.delivery_paper_source_type AS ENUM ('shop_order', 'pbc_costing_file');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'delivery_paper_status') THEN
    CREATE TYPE public.delivery_paper_status AS ENUM (
      'draft', 'packed', 'dispatched', 'delivered', 'cancelled'
    );
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'delivery_paper_line_status') THEN
    CREATE TYPE public.delivery_paper_line_status AS ENUM (
      'packed', 'accepted', 'conditioned', 'rejected'
    );
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.delivery_paper (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_tenant_id bigint NOT NULL REFERENCES public.tenants(id),
  source_type public.delivery_paper_source_type NOT NULL,
  source_id bigint NOT NULL,
  delivery_date date,
  profile_id bigint REFERENCES public.profiles(id),
  note text,
  status public.delivery_paper_status NOT NULL DEFAULT 'draft',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS delivery_paper_source_idx
  ON public.delivery_paper (source_type, source_id);

CREATE INDEX IF NOT EXISTS delivery_paper_parent_profile_idx
  ON public.delivery_paper (parent_tenant_id, profile_id)
  WHERE profile_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.delivery_paper_line (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_paper_id bigint NOT NULL REFERENCES public.delivery_paper(id) ON DELETE CASCADE,
  preorder_demand_id bigint NOT NULL REFERENCES public.preorder_demand(id) ON DELETE CASCADE,
  global_stock_id bigint NOT NULL REFERENCES public.global_stocks(id),
  quantity integer NOT NULL,
  status public.delivery_paper_line_status NOT NULL DEFAULT 'packed',
  note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT delivery_paper_line_quantity_check CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS delivery_paper_line_paper_idx
  ON public.delivery_paper_line (delivery_paper_id);

CREATE INDEX IF NOT EXISTS delivery_paper_line_demand_idx
  ON public.delivery_paper_line (preorder_demand_id);

CREATE UNIQUE INDEX IF NOT EXISTS delivery_paper_line_paper_demand_stock_uidx
  ON public.delivery_paper_line (delivery_paper_id, preorder_demand_id, global_stock_id);

ALTER TABLE public.preorder_demand
  ADD COLUMN IF NOT EXISTS parent_tenant_id bigint REFERENCES public.tenants(id),
  ADD COLUMN IF NOT EXISTS vendor_placements jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS confirmed_quantity integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS open_quantity integer NOT NULL DEFAULT 0;

ALTER TABLE public.preorder_demand
  DROP CONSTRAINT IF EXISTS preorder_demand_vendor_placements_is_array;

ALTER TABLE public.preorder_demand
  ADD CONSTRAINT preorder_demand_vendor_placements_is_array
  CHECK (jsonb_typeof(vendor_placements) = 'array');

CREATE OR REPLACE FUNCTION public.validate_preorder_vendor_placements(p_placements jsonb)
RETURNS boolean
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  v_elem jsonb;
  v_qty integer;
  v_code text;
BEGIN
  IF p_placements IS NULL THEN
    RETURN true;
  END IF;
  IF jsonb_typeof(p_placements) <> 'array' THEN
    RETURN false;
  END IF;
  FOR v_elem IN SELECT value FROM jsonb_array_elements(p_placements)
  LOOP
    v_code := nullif(trim(coalesce(v_elem->>'vendor_code', '')), '');
    v_qty := coalesce((v_elem->>'quantity')::integer, 0);
    IF v_code IS NULL OR v_qty <= 0 THEN
      RETURN false;
    END IF;
  END LOOP;
  RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.sum_preorder_vendor_placements(p_placements jsonb)
RETURNS integer
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT coalesce(
    sum(greatest(coalesce((elem->>'quantity')::integer, 0), 0)),
    0
  )::integer
  FROM jsonb_array_elements(coalesce(p_placements, '[]'::jsonb)) elem;
$$;

CREATE OR REPLACE FUNCTION public.map_stock_pick_close_to_delivery_line_status(p_close_action text)
RETURNS public.delivery_paper_line_status
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE lower(trim(coalesce(p_close_action, 'take')))
    WHEN 'condition' THEN 'conditioned'::public.delivery_paper_line_status
    WHEN 'return' THEN 'rejected'::public.delivery_paper_line_status
    ELSE 'accepted'::public.delivery_paper_line_status
  END;
$$;

CREATE OR REPLACE FUNCTION public.sync_delivery_paper_lines_for_demand(p_preorder_demand_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_pd public.preorder_demand%rowtype;
  v_source_type public.delivery_paper_source_type;
  v_source_id bigint;
  v_paper_id bigint;
  v_elem jsonb;
  v_stock_id bigint;
  v_qty integer;
  v_close text;
  v_line_status public.delivery_paper_line_status;
  v_paper_status public.delivery_paper_status;
BEGIN
  SELECT * INTO v_pd FROM public.preorder_demand WHERE id = p_preorder_demand_id;
  IF NOT FOUND THEN
    RETURN;
  END IF;

  IF v_pd.source_type = 'shop_order_item'::public.preorder_demand_source_type THEN
    v_source_type := 'shop_order'::public.delivery_paper_source_type;
    SELECT oi.order_id INTO v_source_id
    FROM public.shop_order_items oi
    WHERE oi.id = v_pd.source_id;
  ELSE
    v_source_type := 'pbc_costing_file'::public.delivery_paper_source_type;
    SELECT pci.product_based_costing_file_id INTO v_source_id
    FROM public.product_based_costing_items pci
    WHERE pci.id = v_pd.source_id;
  END IF;

  IF v_source_id IS NULL THEN
    RETURN;
  END IF;

  SELECT dp.id INTO v_paper_id
  FROM public.delivery_paper dp
  WHERE dp.source_type = v_source_type
    AND dp.source_id = v_source_id
    AND dp.status <> 'cancelled'::public.delivery_paper_status
  ORDER BY dp.id DESC
  LIMIT 1;

  IF v_paper_id IS NULL THEN
    INSERT INTO public.delivery_paper (
      parent_tenant_id,
      source_type,
      source_id,
      profile_id,
      status
    ) VALUES (
      coalesce(v_pd.parent_tenant_id, public.resolve_parent_tenant_id(v_pd.tenant_id)),
      v_source_type,
      v_source_id,
      v_pd.profile_id,
      'draft'::public.delivery_paper_status
    )
    RETURNING id INTO v_paper_id;
  END IF;

  DELETE FROM public.delivery_paper_line dpl
  WHERE dpl.delivery_paper_id = v_paper_id
    AND dpl.preorder_demand_id = v_pd.id;

  FOR v_elem IN
    SELECT value FROM jsonb_array_elements(coalesce(v_pd.stock_picks, '[]'::jsonb))
  LOOP
    v_stock_id := nullif(v_elem->>'global_stock_id', '')::bigint;
    v_qty := coalesce(
      nullif(v_elem->>'initial_quantity', '')::integer,
      nullif(v_elem->>'quantity', '')::integer,
      0
    );
    IF v_stock_id IS NULL OR v_qty <= 0 THEN
      CONTINUE;
    END IF;
    IF coalesce((v_elem->>'close_split')::boolean, false) THEN
      CONTINUE;
    END IF;
    v_close := lower(trim(coalesce(v_elem->>'close_action', '')));
    IF v_close IN ('take', 'condition', 'return') THEN
      v_line_status := public.map_stock_pick_close_to_delivery_line_status(v_close);
    ELSE
      v_line_status := 'packed'::public.delivery_paper_line_status;
    END IF;

    INSERT INTO public.delivery_paper_line (
      delivery_paper_id,
      preorder_demand_id,
      global_stock_id,
      quantity,
      status,
      note
    ) VALUES (
      v_paper_id,
      v_pd.id,
      v_stock_id,
      v_qty,
      v_line_status,
      nullif(trim(coalesce(v_elem->>'note', '')), '')
    );
  END LOOP;

  SELECT CASE
    WHEN EXISTS (
      SELECT 1 FROM public.delivery_paper_line l
      WHERE l.delivery_paper_id = v_paper_id AND l.status = 'packed'::public.delivery_paper_line_status
    ) THEN 'packed'::public.delivery_paper_status
    WHEN EXISTS (
      SELECT 1 FROM public.delivery_paper_line l
      WHERE l.delivery_paper_id = v_paper_id
    ) THEN 'delivered'::public.delivery_paper_status
    ELSE 'draft'::public.delivery_paper_status
  END INTO v_paper_status;

  UPDATE public.delivery_paper dp
  SET status = v_paper_status, updated_at = now()
  WHERE dp.id = v_paper_id;
END;
$$;

-- Backfill preorder_demand new columns from existing rows + line items.
UPDATE public.preorder_demand pd
SET parent_tenant_id = public.resolve_parent_tenant_id(pd.tenant_id)
WHERE pd.parent_tenant_id IS NULL;

UPDATE public.preorder_demand pd
SET confirmed_quantity = sub.need_qty,
    open_quantity = greatest(sub.need_qty - coalesce(pd.delivered_quantity, 0), 0)
FROM (
  SELECT
    pd2.id,
    CASE
      WHEN pd2.source_type = 'shop_order_item'::public.preorder_demand_source_type THEN
        greatest(coalesce(oi.confirmed_quantity, oi.quantity, 0), 0)::integer
      ELSE
        greatest(
          CASE
            WHEN pci.assigned_shipment_id IS NOT NULL THEN 0
            ELSE coalesce(pci.confirmed_quantity, pci.quantity::integer, 0)
          END,
          0
        )::integer
    END AS need_qty
  FROM public.preorder_demand pd2
  LEFT JOIN public.shop_order_items oi
    ON pd2.source_type = 'shop_order_item'::public.preorder_demand_source_type
    AND oi.id = pd2.source_id
  LEFT JOIN public.product_based_costing_items pci
    ON pd2.source_type = 'pbc_costing_item'::public.preorder_demand_source_type
    AND pci.id = pd2.source_id
) sub
WHERE sub.id = pd.id
  AND pd.confirmed_quantity = 0;

UPDATE public.preorder_demand pd
SET vendor_placements = CASE
  WHEN coalesce(pd.placed_quantity, 0) > 0 THEN
    jsonb_build_array(
      jsonb_build_object(
        'vendor_code', coalesce(nullif(trim(v.code), ''), 'unknown'),
        'quantity', pd.placed_quantity
      )
    )
  ELSE '[]'::jsonb
END
FROM public.vendors v
WHERE v.id = pd.vendor_id
  AND jsonb_array_length(coalesce(pd.vendor_placements, '[]'::jsonb)) = 0
  AND coalesce(pd.placed_quantity, 0) > 0;

UPDATE public.preorder_demand pd
SET vendor_placements = jsonb_build_array(
  jsonb_build_object('vendor_code', 'unknown', 'quantity', pd.placed_quantity)
)
WHERE jsonb_array_length(coalesce(pd.vendor_placements, '[]'::jsonb)) = 0
  AND coalesce(pd.placed_quantity, 0) > 0
  AND pd.vendor_id IS NULL;

UPDATE public.preorder_demand pd
SET open_quantity = greatest(pd.confirmed_quantity - coalesce(pd.delivered_quantity, 0), 0)
WHERE pd.open_quantity = 0 AND pd.confirmed_quantity > 0;

DO $$
DECLARE
  v_id bigint;
BEGIN
  FOR v_id IN SELECT id FROM public.preorder_demand WHERE jsonb_array_length(coalesce(stock_picks, '[]'::jsonb)) > 0
  LOOP
    PERFORM public.sync_delivery_paper_lines_for_demand(v_id);
  END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public.ensure_preorder_demand_for_procuring_document(
  p_document_type text,
  p_document_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_doc_type text := lower(trim(coalesce(p_document_type, '')));
BEGIN
  IF p_document_id IS NULL THEN
    RETURN;
  END IF;

  IF v_doc_type = 'shop_order' THEN
    INSERT INTO public.preorder_demand (
      tenant_id,
      parent_tenant_id,
      source_type,
      source_id,
      profile_id,
      confirmed_quantity,
      open_quantity,
      placed_quantity,
      delivered_quantity,
      vendor_placements,
      stock_picks
    )
    SELECT
      o.tenant_id,
      public.resolve_parent_tenant_id(o.tenant_id),
      'shop_order_item'::public.preorder_demand_source_type,
      oi.id,
      o.profile_id,
      greatest(coalesce(oi.confirmed_quantity, oi.quantity, 0), 0)::integer,
      greatest(coalesce(oi.confirmed_quantity, oi.quantity, 0), 0)::integer,
      0,
      0,
      '[]'::jsonb,
      '[]'::jsonb
    FROM public.shop_order_items oi
    INNER JOIN public.shop_orders o ON o.id = oi.order_id
    WHERE o.id = p_document_id
      AND o.shop_type_snapshot = 'vendor_catalog'
    ON CONFLICT (source_type, source_id) DO UPDATE SET
      profile_id = coalesce(public.preorder_demand.profile_id, excluded.profile_id),
      parent_tenant_id = coalesce(public.preorder_demand.parent_tenant_id, excluded.parent_tenant_id),
      confirmed_quantity = excluded.confirmed_quantity,
      open_quantity = greatest(
        excluded.confirmed_quantity - coalesce(public.preorder_demand.delivered_quantity, 0),
        0
      ),
      updated_at = now();
  ELSIF v_doc_type = 'pbc_costing_file' THEN
    INSERT INTO public.preorder_demand (
      tenant_id,
      parent_tenant_id,
      source_type,
      source_id,
      profile_id,
      confirmed_quantity,
      open_quantity,
      placed_quantity,
      delivered_quantity,
      vendor_placements,
      stock_picks
    )
    SELECT
      f.tenant_id,
      public.resolve_parent_tenant_id(f.tenant_id),
      'pbc_costing_item'::public.preorder_demand_source_type,
      pci.id,
      f.profile_id,
      greatest(
        CASE
          WHEN pci.assigned_shipment_id IS NOT NULL THEN 0
          ELSE coalesce(pci.confirmed_quantity, pci.quantity::integer, 0)
        END,
        0
      )::integer,
      greatest(
        CASE
          WHEN pci.assigned_shipment_id IS NOT NULL THEN 0
          ELSE coalesce(pci.confirmed_quantity, pci.quantity::integer, 0)
        END,
        0
      )::integer,
      0,
      0,
      '[]'::jsonb,
      '[]'::jsonb
    FROM public.product_based_costing_items pci
    INNER JOIN public.product_based_costing_files f ON f.id = pci.product_based_costing_file_id
    WHERE f.id = p_document_id
    ON CONFLICT (source_type, source_id) DO UPDATE SET
      profile_id = coalesce(public.preorder_demand.profile_id, excluded.profile_id),
      parent_tenant_id = coalesce(public.preorder_demand.parent_tenant_id, excluded.parent_tenant_id),
      confirmed_quantity = excluded.confirmed_quantity,
      open_quantity = greatest(
        excluded.confirmed_quantity - coalesce(public.preorder_demand.delivered_quantity, 0),
        0
      ),
      updated_at = now();
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.upsert_preorder_demand(
  p_tenant_id bigint,
  p_source_type public.preorder_demand_source_type,
  p_source_id bigint,
  p_vendor_id bigint DEFAULT NULL,
  p_placed_quantity integer DEFAULT NULL,
  p_stock_picks jsonb DEFAULT NULL,
  p_notes text DEFAULT NULL
)
RETURNS public.preorder_demand
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row public.preorder_demand;
  v_line_tenant_id bigint;
  v_doc_status text;
  v_open_qty integer;
  v_delivered integer;
  v_placed integer;
  v_placements jsonb;
  v_vendor_code text;
BEGIN
  IF p_tenant_id IS NULL THEN
    RAISE EXCEPTION 'tenant_id is required';
  END IF;
  IF p_source_id IS NULL THEN
    RAISE EXCEPTION 'source_id is required';
  END IF;

  SELECT g.tenant_id, g.open_qty, g.document_status
  INTO v_line_tenant_id, v_open_qty, v_doc_status
  FROM public.get_procurement_demand_open_qty(p_source_type, p_source_id) g;

  IF v_line_tenant_id IS NULL THEN
    RAISE EXCEPTION 'demand line not found';
  END IF;

  IF NOT public.can_access_preorder_demand_tenant(p_tenant_id)
    AND NOT public.can_access_preorder_demand_tenant(v_line_tenant_id) THEN
    RAISE EXCEPTION 'access denied';
  END IF;

  IF v_line_tenant_id <> p_tenant_id THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.tenants t
      WHERE t.id = v_line_tenant_id
        AND t.parent_id = p_tenant_id
        AND public.user_can_manage_parent_tenant(p_tenant_id)
    ) THEN
      RAISE EXCEPTION 'tenant mismatch for demand line';
    END IF;
  END IF;

  IF v_doc_status NOT IN ('procuring', 'packed') THEN
    RAISE EXCEPTION 'document is not open for preorder demand updates';
  END IF;

  IF p_placed_quantity IS NOT NULL AND v_doc_status <> 'procuring' THEN
    RAISE EXCEPTION 'placed_quantity can only be updated while procuring';
  END IF;

  IF p_stock_picks IS NOT NULL AND v_doc_status NOT IN ('procuring', 'packed') THEN
    RAISE EXCEPTION 'stock_picks can only be updated while procuring or packed';
  END IF;

  IF p_placed_quantity IS NOT NULL AND coalesce(p_placed_quantity, 0) < 0 THEN
    RAISE EXCEPTION 'placed_quantity cannot be negative';
  END IF;

  IF p_stock_picks IS NOT NULL AND NOT public.validate_preorder_stock_picks(p_stock_picks) THEN
    RAISE EXCEPTION 'invalid stock_picks payload';
  END IF;

  v_delivered := CASE
    WHEN p_stock_picks IS NOT NULL THEN public.sum_preorder_stock_picks(p_stock_picks)
    ELSE NULL
  END;

  SELECT pd.* INTO v_row
  FROM public.preorder_demand pd
  WHERE pd.source_type = p_source_type
    AND pd.source_id = p_source_id;

  IF p_placed_quantity IS NOT NULL THEN
    SELECT nullif(trim(v.code), '') INTO v_vendor_code
    FROM public.vendors v
    WHERE v.id = coalesce(p_vendor_id, v_row.vendor_id);
    v_vendor_code := coalesce(v_vendor_code, 'unknown');
    v_placements := jsonb_build_array(
      jsonb_build_object('vendor_code', v_vendor_code, 'quantity', p_placed_quantity)
    );
    IF NOT public.validate_preorder_vendor_placements(v_placements) THEN
      RAISE EXCEPTION 'invalid vendor_placements payload';
    END IF;
  ELSE
    v_placements := NULL;
  END IF;

  IF found THEN
    v_placed := coalesce(
      CASE WHEN v_placements IS NOT NULL THEN public.sum_preorder_vendor_placements(v_placements) END,
      public.sum_preorder_vendor_placements(v_row.vendor_placements),
      v_row.placed_quantity,
      0
    );
  ELSE
    v_placed := coalesce(public.sum_preorder_vendor_placements(v_placements), 0);
  END IF;

  IF v_delivered IS NOT NULL AND v_delivered > coalesce(v_open_qty, 0) THEN
    RAISE EXCEPTION 'delivered_quantity cannot exceed need quantity';
  END IF;

  INSERT INTO public.preorder_demand (
    tenant_id,
    parent_tenant_id,
    source_type,
    source_id,
    vendor_id,
    placed_quantity,
    delivered_quantity,
    vendor_placements,
    stock_picks,
    notes,
    updated_by_user_id
  ) VALUES (
    v_line_tenant_id,
    public.resolve_parent_tenant_id(v_line_tenant_id),
    p_source_type,
    p_source_id,
    coalesce(p_vendor_id, CASE WHEN found THEN v_row.vendor_id ELSE NULL END),
    v_placed,
    coalesce(v_delivered, CASE WHEN found THEN v_row.delivered_quantity ELSE 0 END, 0),
    coalesce(v_placements, CASE WHEN found THEN v_row.vendor_placements ELSE '[]'::jsonb END, '[]'::jsonb),
    coalesce(p_stock_picks, CASE WHEN found THEN v_row.stock_picks ELSE '[]'::jsonb END, '[]'::jsonb),
    coalesce(nullif(trim(p_notes), ''), CASE WHEN found THEN v_row.notes ELSE NULL END),
    auth.uid()
  )
  ON CONFLICT (source_type, source_id) DO UPDATE SET
    parent_tenant_id = coalesce(public.preorder_demand.parent_tenant_id, excluded.parent_tenant_id),
    vendor_id = CASE WHEN p_vendor_id IS NOT NULL THEN p_vendor_id ELSE preorder_demand.vendor_id END,
    placed_quantity = v_placed,
    vendor_placements = CASE
      WHEN v_placements IS NOT NULL THEN v_placements
      ELSE preorder_demand.vendor_placements
    END,
    delivered_quantity = CASE
      WHEN v_delivered IS NOT NULL THEN v_delivered
      ELSE preorder_demand.delivered_quantity
    END,
    open_quantity = greatest(
      coalesce(preorder_demand.confirmed_quantity, 0)
        - CASE WHEN v_delivered IS NOT NULL THEN v_delivered ELSE preorder_demand.delivered_quantity END,
      0
    ),
    stock_picks = CASE WHEN p_stock_picks IS NOT NULL THEN p_stock_picks ELSE preorder_demand.stock_picks END,
    notes = CASE WHEN p_notes IS NOT NULL THEN nullif(trim(p_notes), '') ELSE preorder_demand.notes END,
    updated_by_user_id = auth.uid(),
    updated_at = now()
  RETURNING * INTO v_row;

  IF p_stock_picks IS NOT NULL OR jsonb_array_length(coalesce(v_row.stock_picks, '[]'::jsonb)) > 0 THEN
    PERFORM public.sync_delivery_paper_lines_for_demand(v_row.id);
  END IF;

  RETURN v_row;
END;
$$;

-- Expose vendor_placements on demand list items (placed_quantity still synced for UI).
CREATE OR REPLACE FUNCTION public.list_procurement_demand_group_items(
  p_tenant_id bigint,
  p_document_type text,
  p_document_id bigint,
  p_search text DEFAULT NULL,
  p_limit integer DEFAULT 50,
  p_cursor_source_id bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_doc_type text := lower(trim(coalesce(p_document_type, '')));
  v_is_parent boolean;
  v_allowed boolean := false;
  v_search text := nullif(trim(coalesce(p_search, '')), '');
  v_limit integer := greatest(1, least(coalesce(p_limit, 50), 100));
  v_items jsonb := '[]'::jsonb;
  v_n integer := 0;
  v_has_more boolean := false;
  v_next_cursor jsonb := null;
  v_last_source_id bigint;
BEGIN
  IF p_tenant_id IS NULL OR p_document_id IS NULL THEN
    RAISE EXCEPTION 'tenant_id and document_id are required';
  END IF;

  SELECT (t.parent_id IS NULL) INTO v_is_parent FROM public.tenants t WHERE t.id = p_tenant_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'tenant not found: %', p_tenant_id; END IF;

  IF v_is_parent THEN
    v_allowed := public.user_can_manage_parent_tenant(p_tenant_id);
  ELSE
    v_allowed := public.is_tenant_staff(p_tenant_id);
  END IF;
  IF NOT coalesce(v_allowed, false) THEN RAISE EXCEPTION 'access denied'; END IF;

  IF v_doc_type NOT IN ('shop_order', 'pbc_costing_file') THEN
    RAISE EXCEPTION 'invalid document_type: %', p_document_type;
  END IF;

  WITH tenant_scope AS (
    SELECT t.id AS tenant_id FROM public.tenants t
    WHERE (
      (v_is_parent AND (t.parent_id = p_tenant_id OR t.id = p_tenant_id))
      OR (NOT v_is_parent AND t.id = p_tenant_id)
    )
  ),
  shop_lines AS (
    SELECT
      'shop_order'::text AS document_type,
      o.id AS document_id,
      'shop_order_item'::text AS source_type,
      oi.id AS source_id,
      oi.product_id,
      oi.name,
      oi.image_url,
      coalesce(p.barcode, '') AS barcode,
      coalesce(p.product_code, '') AS product_code,
      nullif(trim(coalesce(p.vendor_code, '')), '') AS vendor_code,
      nullif(trim(coalesce(p.market_code, '')), '') AS market_code,
      nullif(trim(coalesce(p.brand, '')), '') AS brand,
      nullif(trim(coalesce(p.category, '')), '') AS category,
      p.available_units,
      nullif(trim(coalesce(p.languages, '')), '') AS languages,
      nullif(trim(coalesce(p.country_of_origin, '')), '') AS country_of_origin,
      greatest(coalesce(oi.confirmed_quantity, oi.quantity, 0), 0)::integer AS quantity,
      pd.id AS preorder_demand_id,
      pd.vendor_id,
      coalesce(public.sum_preorder_vendor_placements(pd.vendor_placements), pd.placed_quantity, 0) AS placed_quantity,
      coalesce(pd.delivered_quantity, 0) AS delivered_quantity,
      coalesce(pd.vendor_placements, '[]'::jsonb) AS vendor_placements,
      coalesce(pd.stock_picks, '[]'::jsonb) AS stock_picks
    FROM public.shop_order_items oi
    INNER JOIN public.shop_orders o ON o.id = oi.order_id
    INNER JOIN tenant_scope ts ON ts.tenant_id = o.tenant_id
    LEFT JOIN public.products p ON p.id = oi.product_id
    LEFT JOIN public.preorder_demand pd
      ON pd.source_type = 'shop_order_item'
      AND pd.source_id = oi.id
      AND pd.tenant_id = o.tenant_id
    WHERE v_doc_type = 'shop_order'
      AND o.id = p_document_id
      AND o.shop_type_snapshot = 'vendor_catalog'
  ),
  pbc_lines AS (
    SELECT
      'pbc_costing_file'::text AS document_type,
      f.id AS document_id,
      'pbc_costing_item'::text AS source_type,
      pci.id AS source_id,
      pci.product_id,
      coalesce(pci.name, p.name, 'Item') AS name,
      coalesce(pci.image_url, p.image_url) AS image_url,
      coalesce(pci.barcode, p.barcode, '') AS barcode,
      coalesce(pci.product_code, p.product_code, '') AS product_code,
      coalesce(
        nullif(trim(coalesce(pci.vendor_code, '')), ''),
        nullif(trim(coalesce(p.vendor_code, '')), '')
      ) AS vendor_code,
      coalesce(
        nullif(trim(coalesce(pci.market_code, '')), ''),
        nullif(trim(coalesce(p.market_code, '')), '')
      ) AS market_code,
      coalesce(
        nullif(trim(coalesce(pci.brand, '')), ''),
        nullif(trim(coalesce(p.brand, '')), '')
      ) AS brand,
      nullif(trim(coalesce(p.category, '')), '') AS category,
      p.available_units,
      nullif(trim(coalesce(p.languages, '')), '') AS languages,
      nullif(trim(coalesce(p.country_of_origin, '')), '') AS country_of_origin,
      greatest(
        CASE WHEN pci.assigned_shipment_id IS NOT NULL THEN 0
          ELSE coalesce(pci.confirmed_quantity, pci.quantity::integer, 0)
        END,
        0
      )::integer AS quantity,
      pd.id AS preorder_demand_id,
      pd.vendor_id,
      coalesce(public.sum_preorder_vendor_placements(pd.vendor_placements), pd.placed_quantity, 0) AS placed_quantity,
      coalesce(pd.delivered_quantity, 0) AS delivered_quantity,
      coalesce(pd.vendor_placements, '[]'::jsonb) AS vendor_placements,
      coalesce(pd.stock_picks, '[]'::jsonb) AS stock_picks
    FROM public.product_based_costing_items pci
    INNER JOIN public.product_based_costing_files f ON f.id = pci.product_based_costing_file_id
    INNER JOIN tenant_scope ts ON ts.tenant_id = f.tenant_id
    LEFT JOIN public.products p ON p.id = pci.product_id
    LEFT JOIN public.preorder_demand pd
      ON pd.source_type = 'pbc_costing_item'
      AND pd.source_id = pci.id
      AND pd.tenant_id = f.tenant_id
    WHERE v_doc_type = 'pbc_costing_file'
      AND f.id = p_document_id
      AND f.profile_id IS NOT NULL
  ),
  demand_lines AS (
    SELECT * FROM shop_lines
    UNION ALL
    SELECT * FROM pbc_lines
  ),
  eligible_lines AS (
    SELECT dl.*
    FROM demand_lines dl
    WHERE (
      dl.quantity > 0
      OR dl.placed_quantity > 0
      OR dl.delivered_quantity > 0
    )
      AND (
        v_search IS NULL
        OR dl.name ILIKE '%' || v_search || '%'
        OR coalesce(dl.barcode, '') ILIKE '%' || v_search || '%'
        OR coalesce(dl.product_code, '') ILIKE '%' || v_search || '%'
      )
      AND (
        p_cursor_source_id IS NULL
        OR dl.source_id > p_cursor_source_id
      )
  ),
  paged AS (
    SELECT el.*
    FROM eligible_lines el
    ORDER BY el.source_id
    LIMIT v_limit + 1
  ),
  page_count AS (
    SELECT count(*)::integer AS n FROM paged
  ),
  page_rows AS (
    SELECT p.*
    FROM paged p
    ORDER BY p.source_id
    LIMIT v_limit
  ),
  item_json AS (
    SELECT coalesce(
      jsonb_agg(
        jsonb_build_object(
          'source_type', row.source_type,
          'source_id', row.source_id,
          'product_id', row.product_id,
          'name', row.name,
          'image_url', row.image_url,
          'barcode', nullif(row.barcode, ''),
          'product_code', nullif(row.product_code, ''),
          'vendor_code', row.vendor_code,
          'market_code', row.market_code,
          'brand', row.brand,
          'category', row.category,
          'available_units', row.available_units,
          'languages', row.languages,
          'country_of_origin', row.country_of_origin,
          'quantity', row.quantity,
          'need_quantity', row.quantity,
          'preorder_demand_id', row.preorder_demand_id,
          'vendor_id', row.vendor_id,
          'placed_quantity', row.placed_quantity,
          'vendor_placements', row.vendor_placements,
          'delivered_quantity', row.delivered_quantity,
          'remaining_quantity', row.quantity - row.placed_quantity,
          'remaining_to_deliver', greatest(row.quantity - row.delivered_quantity, 0),
          'stock_picks', row.stock_picks
        )
        ORDER BY row.source_id
      ),
      '[]'::jsonb
    ) AS items
    FROM page_rows row
  ),
  cursor_row AS (
    SELECT p.source_id
    FROM paged p
    ORDER BY p.source_id
    OFFSET v_limit
    LIMIT 1
  )
  SELECT
    ij.items,
    pc.n,
    cr.source_id
  INTO v_items, v_n, v_last_source_id
  FROM item_json ij
  CROSS JOIN page_count pc
  LEFT JOIN cursor_row cr ON true;

  v_has_more := v_n > v_limit;
  IF v_has_more AND v_last_source_id IS NOT NULL THEN
    v_next_cursor := jsonb_build_object('source_id', v_last_source_id);
  END IF;

  RETURN jsonb_build_object(
    'meta', jsonb_build_object(
      'document_type', v_doc_type,
      'document_id', p_document_id,
      'limit', v_limit,
      'has_more', v_has_more,
      'next_cursor', v_next_cursor
    ),
    'items', v_items
  );
END;
$$;

